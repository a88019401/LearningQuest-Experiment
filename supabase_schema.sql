create extension if not exists pgcrypto;

-- ----------------------------------------------------------------------------
-- 1. profiles：一位 Auth 使用者對應一筆個人資料與完整學習進度 JSONB
-- ----------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  updated_at timestamptz default now(),
  username text,
  full_name text,
  school text,
  grade text,
  progress jsonb not null default '{}'::jsonb
);

-- 舊資料庫若是由早期 SQL 建立，補上前端目前必要欄位。
alter table public.profiles add column if not exists updated_at timestamptz default now();
alter table public.profiles add column if not exists username text;
alter table public.profiles add column if not exists full_name text;
alter table public.profiles add column if not exists school text;
alter table public.profiles add column if not exists grade text;
alter table public.profiles add column if not exists progress jsonb default '{}'::jsonb;

update public.profiles
set progress = '{}'::jsonb
where progress is null;

alter table public.profiles alter column progress set default '{}'::jsonb;
alter table public.profiles alter column progress set not null;

create index if not exists profiles_grade_idx on public.profiles (grade);
create index if not exists profiles_full_name_idx on public.profiles (full_name);
create index if not exists profiles_progress_gin_idx on public.profiles using gin (progress);

alter table public.profiles enable row level security;

drop policy if exists "Users can view their own profile." on public.profiles;
create policy "Users can view their own profile."
  on public.profiles
  for select
  to authenticated
  using (auth.uid() = id);

drop policy if exists "Users can create their own profile." on public.profiles;
create policy "Users can create their own profile."
  on public.profiles
  for insert
  to authenticated
  with check (auth.uid() = id);

drop policy if exists "Users can update their own profile." on public.profiles;
create policy "Users can update their own profile."
  on public.profiles
  for update
  to authenticated
  using (auth.uid() = id)
  with check (auth.uid() = id);

-- ProfileSetup 使用 UPDATE，因此註冊後必須先自動建立空白 profile。
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, updated_at, progress)
  values (new.id, now(), '{}'::jsonb)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- 若 Auth 已經有舊帳號，但 profiles 缺列，可補建空白列。
insert into public.profiles (id, updated_at, progress)
select u.id, now(), '{}'::jsonb
from auth.users u
left join public.profiles p on p.id = u.id
where p.id is null;

-- ----------------------------------------------------------------------------
-- 2. leaderboard：貪吃蛇與文法方塊的每人最佳成績
-- ----------------------------------------------------------------------------
create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  full_name text,
  game text not null,
  score integer not null,
  created_at timestamptz default now(),
  constraint unique_user_game unique (user_id, game),
  constraint leaderboard_game_check check (game in ('snake', 'tetris')),
  constraint leaderboard_score_check check (score >= 0)
);

create index if not exists leaderboard_game_score_idx
  on public.leaderboard (game, score desc);
create index if not exists leaderboard_user_id_idx
  on public.leaderboard (user_id);

alter table public.leaderboard enable row level security;

-- 排行榜必須允許已登入學生查看所有人的公開排名欄位。
drop policy if exists "Authenticated users can view leaderboard" on public.leaderboard;
create policy "Authenticated users can view leaderboard"
  on public.leaderboard
  for select
  to authenticated
  using (true);

-- 僅能新增自己的成績。
drop policy if exists "Users can insert own leaderboard score" on public.leaderboard;
create policy "Users can insert own leaderboard score"
  on public.leaderboard
  for insert
  to authenticated
  with check (auth.uid() = user_id);

-- 僅能更新自己的成績；前端 upsert 需要 UPDATE 權限。
drop policy if exists "Users can update own leaderboard score" on public.leaderboard;
create policy "Users can update own leaderboard score"
  on public.leaderboard
  for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

