-- ----------------------------------------------------------------------------
-- 4. badge_leaderboard_ranked：由 profiles.progress.badges 即時計算獎章排名
-- ----------------------------------------------------------------------------
-- profiles 的 RLS 僅允許學生讀自己的 row；若直接建立 security_invoker view，
-- 一般學生只能看到自己。以下以 SECURITY DEFINER 函式只公開必要的彙總欄位，
-- 不直接暴露完整 progress JSONB。

create or replace function public.get_badge_leaderboard_ranked()
returns table (
  id uuid,
  full_name text,
  gold integer,
  silver integer,
  bronze integer,
  score integer
)
language sql
stable
security definer
set search_path = ''
as $$
  with badge_rows as (
    select
      p.id,
      p.full_name,
      case
        when jsonb_typeof(b.value) = 'object'
          and coalesce(b.value ->> 'tier', '') ~ '^[0-9]+$'
        then (b.value ->> 'tier')::integer
        else 0
      end as tier
    from public.profiles p
    left join lateral jsonb_each(
      coalesce(p.progress -> 'badges', '{}'::jsonb)
    ) as b(key, value) on true
  ),
  ranked as (
    select
      badge_rows.id,
      badge_rows.full_name,
      count(*) filter (where badge_rows.tier = 3)::integer as gold,
      count(*) filter (where badge_rows.tier = 2)::integer as silver,
      count(*) filter (where badge_rows.tier = 1)::integer as bronze,
      (
        count(*) filter (where badge_rows.tier = 3) * 5
        + count(*) filter (where badge_rows.tier = 2) * 3
        + count(*) filter (where badge_rows.tier = 1)
      )::integer as score
    from badge_rows
    group by badge_rows.id, badge_rows.full_name
  )
  select
    ranked.id,
    ranked.full_name,
    ranked.gold,
    ranked.silver,
    ranked.bronze,
    ranked.score
  from ranked
  where ranked.full_name is not null
    and btrim(ranked.full_name) <> ''
    and (ranked.gold + ranked.silver + ranked.bronze) > 0;
$$;

revoke all on function public.get_badge_leaderboard_ranked() from public;
grant execute on function public.get_badge_leaderboard_ranked() to authenticated;

create or replace view public.badge_leaderboard_ranked
with (security_invoker = true) as
select * from public.get_badge_leaderboard_ranked();

grant select on public.badge_leaderboard_ranked to authenticated;

-- ----------------------------------------------------------------------------
-- 5. 明確授權（RLS 仍會繼續限制 row）
-- ----------------------------------------------------------------------------
grant select, insert, update on public.profiles to authenticated;
grant select, insert, update on public.leaderboard to authenticated;
grant insert on public.lsa_logs to authenticated;
do $$
begin
  if to_regclass('public.leaderboard_id_seq') is not null then
    execute 'grant usage, select on sequence public.leaderboard_id_seq to authenticated';
  end if;
end;
$$;

commit;

