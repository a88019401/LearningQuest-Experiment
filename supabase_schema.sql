create index if not exists lsa_logs_user_created_idx
  on public.lsa_logs (user_id, created_at);
create index if not exists lsa_logs_session_created_idx
  on public.lsa_logs (session_id, created_at);
create index if not exists lsa_logs_action_state_idx
  on public.lsa_logs (action_state);
create index if not exists lsa_logs_context_data_gin_idx
  on public.lsa_logs using gin (context_data);

alter table public.lsa_logs enable row level security;

drop policy if exists "users can insert own lsa logs" on public.lsa_logs;
create policy "users can insert own lsa logs"
  on public.lsa_logs
  for insert
  to authenticated
  with check (auth.uid() = user_id);

